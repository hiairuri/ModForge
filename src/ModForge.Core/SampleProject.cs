using ModForge.Core.Model;

namespace ModForge.Core;

/// <summary>
/// A small sample project used to exercise the whole pipeline. It is also the
/// starting point a user sees in the editor, so it should look like a real card set
/// rather than a single throwaway card.
/// </summary>
public static class SampleProject
{
    public static ModProject Create()
    {
        var emberMight = new PowerDef
        {
            Id = "EMBER_MIGHT",
            Name = new LocalizedText("eng", "Ember Might").With("zhs", "余烬之力"),
            Description = new LocalizedText("eng", "Your attacks deal {Amount} additional damage. Lose 1 stack at the end of your turn.")
                .With("zhs", "你的攻击额外造成 {Amount} 点伤害。在你的回合结束时失去 1 层。"),
            Kind = PowerKind.Buff,
            Stack = PowerStack.Counter,
            DamageModifier = DamageModifier.Additive,
            Decay = DecayMode.OnePerTurnEnd,
        };

        var smolder = new PowerDef
        {
            Id = "SMOLDER",
            Name = new LocalizedText("eng", "Smolder").With("zhs", "阴燃"),
            Description = new LocalizedText("eng", "At the start of your turn, take {Amount} damage.")
                .With("zhs", "在你的回合开始时，受到 {Amount} 点伤害。"),
            Kind = PowerKind.Debuff,
            Stack = PowerStack.Counter,
            Decay = DecayMode.OnePerTurnEnd,
            Triggers =
            {
                new TriggeredEffect
                {
                    When = PowerTrigger.TurnStart,
                    Effect = new EffectDef
                    {
                        Kind = EffectKind.LoseHp,
                        Target = EffectTarget.Self,
                        Amount = 2,
                    },
                },
            },
        };

        var project = new ModProject
        {
            Id = "EmberForge",
            Name = "Ember Forge",
            Author = "ModForge",
            Description = "A small sample content pack generated by ModForge.",
            Version = "1.0.0",
            SelfCheckOnStartup = true,
        };

        project.Powers.Add(emberMight);
        project.Powers.Add(smolder);

        project.Cards.Add(new CardDef
        {
            Id = "EMBER_STRIKE",
            Name = new LocalizedText("eng", "Ember Strike").With("zhs", "余烬打击"),
            Description = new LocalizedText("eng", "Deal {Damage:diff()} damage.\nGain {EmberMightPower:diff()} Ember Might.")
                .With("zhs", "造成 {Damage:diff()} 点伤害。\n获得 {EmberMightPower:diff()} 层余烬之力。"),
            Pool = "ironclad",
            Type = CardType.Attack,
            Rarity = CardRarity.Common,
            Target = CardTargetType.AnyEnemy,
            EnergyCost = 1,
            Effects =
            {
                new EffectDef { Kind = EffectKind.DealDamage, Target = EffectTarget.Target, Amount = 8, Upgrade = new EffectUpgrade { AmountDelta = 3 } },
                new EffectDef
                {
                    Kind = EffectKind.ApplyPower,
                    Target = EffectTarget.Self,
                    PowerId = "EMBER_MIGHT",
                    Amount = 2,
                },
            },
        });

        project.Cards.Add(new CardDef
        {
            Id = "EMBER_WARD",
            Name = new LocalizedText("eng", "Ember Ward").With("zhs", "余烬守护"),
            Description = new LocalizedText("eng", "Gain {Block:diff()} [gold]Block[/gold].\nDraw 1 card.")
                .With("zhs", "获得 {Block:diff()} 点[gold]格挡[/gold]。\n抽 1 张牌。"),
            Pool = "ironclad",
            Type = CardType.Skill,
            Rarity = CardRarity.Common,
            Target = CardTargetType.Self,
            EnergyCost = 1,
            Effects =
            {
                new EffectDef { Kind = EffectKind.GainBlock, Target = EffectTarget.Self, Amount = 6, Upgrade = new EffectUpgrade { AmountDelta = 3 } },
                new EffectDef { Kind = EffectKind.DrawCards, Target = EffectTarget.Self, Amount = 1 },
            },
        });

        project.Cards.Add(new CardDef
        {
            Id = "EMBER_BURST",
            Name = new LocalizedText("eng", "Ember Burst").With("zhs", "余烬爆发"),
            Description = new LocalizedText("eng", "Deal {Damage:diff()} damage to ALL enemies.\nApply 2 Smolder to ALL enemies.\nExhaust.")
                .With("zhs", "对所有敌人造成 {Damage:diff()} 点伤害。\n对所有敌人施加 2 层阴燃。\n消耗。"),
            Pool = "ironclad",
            Type = CardType.Attack,
            Rarity = CardRarity.Rare,
            Target = CardTargetType.AllEnemies,
            EnergyCost = 2,
            Keywords = { CardKeyword.Exhaust },
            Effects =
            {
                new EffectDef { Kind = EffectKind.DealDamage, Target = EffectTarget.AllEnemies, Amount = 14, Upgrade = new EffectUpgrade { AmountDelta = 5 } },
                new EffectDef
                {
                    Kind = EffectKind.ApplyPower,
                    Target = EffectTarget.AllEnemies,
                    PowerId = "SMOLDER",
                    Amount = 2,
                },
            },
        });

        project.Cards.Add(new CardDef
        {
            Id = "EMBER_BULWARK",
            Name = new LocalizedText("eng", "Ember Bulwark").With("zhs", "余烬壁垒"),
            Description = new LocalizedText("eng", "Gain {Block:diff()} [gold]Block[/gold].\nHeal HP equal to your Block.")
                .With("zhs", "获得 {Block:diff()} 点[gold]格挡[/gold]。\n回复等同于格挡值的生命。"),
            Pool = "ironclad",
            Type = CardType.Skill,
            Rarity = CardRarity.Uncommon,
            Target = CardTargetType.Self,
            EnergyCost = 2,
            Effects =
            {
                new EffectDef { Kind = EffectKind.GainBlock, Target = EffectTarget.Self, Amount = 5, Upgrade = new EffectUpgrade { AmountDelta = 3 } },
                new EffectDef
                {
                    Kind = EffectKind.Heal,
                    Target = EffectTarget.Self,

                    // 回复量等于自身格挡：用计算型数值表达，而不是固定数字。
                    // （"是不是计算型"由有没有来源决定，没有单独的开关。）
                    Source = new ValueSource
                    {
                        Actor = ValueSourceActor.Self,
                        Kind = ValueSourceKind.Block,
                        PerUnit = 1m,
                    },
                },
            },
        });

        return project;
    }
}

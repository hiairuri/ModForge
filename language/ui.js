/** 当前界面语言，以及取文案的助手。 */
let uiLanguage = 'zh';

function t(key, vars) {
  const table = I18N[uiLanguage] || I18N.en;
  let text = table[key] ?? I18N.en[key] ?? key;

  if (vars) {
    Object.entries(vars).forEach(([k, v]) => {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    });
  }

  return text;
}
